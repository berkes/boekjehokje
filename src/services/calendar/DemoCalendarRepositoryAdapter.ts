/**
 * Demo calendar repository adapter
 *
 * The repository that fulfils the CalendarEventRepositoryPort with demo
 * data: one huge, fully hardcoded array of bookings - room, booker,
 * summary, demo week, weekday and times all in the array, like a JSON
 * fixture. The only two things filled in at runtime, in one pass over
 * the array, are the actual dates (each booking is placed in its demo
 * week relative to the current week, per the clock) and the creator
 * email of the bookings marked editable, which becomes the given user's
 * email - whether that makes them editable is the permission service's
 * call, exactly like for the real calendar. Used by the demo page to
 * review and screenshot all calendar states without touching the real
 * NYMA calendar.
 */

